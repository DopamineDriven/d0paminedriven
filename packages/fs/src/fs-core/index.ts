import fsAsync from "fs/promises";
import fsSync from "node:fs";
import { relative } from "path";
import type {
  WriteableDataType,
  WriteFileAsyncOptions,
  WriteStreamOptions
} from "@/types/index.ts";
import { FsSize } from "@/fs-size/index.ts";

export class FsCore extends FsSize {
  constructor(public cwd: string) {
    super((cwd ??= process.cwd()));
  }

  public withWs<const T extends string>(
    path: T,
    data: WriteableDataType,
    options?: WriteStreamOptions
  ) {
    try {
      if (/\//g.test(path) === true) {
        return this.generateDirIfDNE(this.pathHandler(path), {
          recursive: true
        });
      } else return path;
    } catch (error) {
      console.error(
        `[withWs error]: `.concat(
          typeof error === "string" ? error : JSON.stringify(error, null, 2)
        )
      );
    } finally {
      return fsSync
        .createWriteStream(
          relative(this.cwd ?? process.cwd(), path),
          typeof options !== "undefined"
            ? typeof options === "object"
              ? options
              : options
            : { autoClose: true }
        )
        .write(data);
    }
  }
  public async withWsAsync<const T extends string>(
    path: T,
    data: WriteableDataType,
    options?: WriteStreamOptions
  ) {
    try {
      if (/\//g.test(path) === true) {
        return this.generateDirIfDNE(this.pathHandler(path), {
          recursive: true
        });
      } else return path;
    } catch (error) {
      console.error(
        `[withWs error]: `.concat(
          typeof error === "string" ? error : JSON.stringify(error, null, 2)
        )
      );
    } finally {
      return fsSync
        .createWriteStream(
          relative(this.cwd ?? process.cwd(), path),
          typeof options !== "undefined"
            ? typeof options === "object"
              ? options
              : options
            : { autoClose: true }
        )
        .write(data);
    }
  }

  public writeFileAsync = async <const T extends string>(
    path: T,
    data:
      | string
      | NodeJS.ArrayBufferView
      | Iterable<string | NodeJS.ArrayBufferView>
      | AsyncIterable<string | NodeJS.ArrayBufferView>,
    options: WriteFileAsyncOptions = {}
  ) => {
    try {
      if (/\//g.test(path) === true)
        return this.generateDirIfDNE(this.pathHandler(path), {
          recursive: true
        });
      else return path;
    } catch (error) {
      console.error(
        `[writeFileAsync error]: `.concat(
          error instanceof Error
            ? error.message
            : typeof error === "string"
              ? error
              : JSON.stringify(error, null, 2)
        )
      );
    } finally {
      return fsAsync.writeFile(relative(this.cwd, path), data, options);
    }
  };
}
